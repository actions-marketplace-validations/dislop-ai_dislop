#!/usr/bin/env node
// Zero-dependency static builder for site/.
// Syncs src/core.mjs, assets/logo.svg, and packs/<id>/pack.json into site/
// so the browser workbench runs the exact same engine and rules as the CLI.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SITE_DIR = path.join(ROOT, "site");
const ENGINE_OUT = path.join(SITE_DIR, "engine");
const ASSETS_OUT = path.join(SITE_DIR, "assets");

fs.mkdirSync(ENGINE_OUT, { recursive: true });
fs.mkdirSync(ASSETS_OUT, { recursive: true });

// 1. Copy shared zero-dep engine
fs.copyFileSync(path.join(ROOT, "src", "core.mjs"), path.join(ENGINE_OUT, "core.mjs"));

// 2. Copy brand mark SVG
fs.copyFileSync(path.join(ROOT, "assets", "logo.svg"), path.join(ASSETS_OUT, "logo.svg"));

// 3. Compile packs/*/pack.json into an ES module
const packsDir = path.join(ROOT, "packs");
const packsById = {};
for (const entry of fs.readdirSync(packsDir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue;
  const p = path.join(packsDir, entry.name, "pack.json");
  if (fs.existsSync(p)) {
    const manifest = JSON.parse(fs.readFileSync(p, "utf8"));
    packsById[manifest.id] = manifest;
  }
}

const packsModule = `// Auto-generated by scripts/build_site.mjs from packs/*/pack.json — do not hand-edit.\nexport const PACKS_BY_ID = ${JSON.stringify(packsById, null, 2)};\n`;
fs.writeFileSync(path.join(ENGINE_OUT, "packs-data.mjs"), packsModule, "utf8");

console.log(`Built site bundle: synced core.mjs, logo.svg, and ${Object.keys(packsById).length} packs into site/`);
